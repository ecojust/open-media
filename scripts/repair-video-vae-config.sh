app_data="${1:-$HOME/Library/Application Support/com.ecojust.openmedia}"
revision='42ed227ee7df40d41602854ae760620d6eb651fe'
expected='3edd2cdd1ebc823c868be55ef917e1b3b8a398fde4d3150dae44a3bf05d9f627'
temporary=''
trap 'if [ -n "$temporary" ]; then rm -f "$temporary"; fi' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Complete original notices travel with this standalone script. Existing notices
# are never overwritten; new files are linked into place without replacing a race.
ensure_model_notice() {
  local destination="$1" writer="$2"
  if [ -e "$destination" ] || [ -L "$destination" ]; then
    return
  fi
  temporary="$(mktemp "$(dirname "$destination")/.open-media-notice.XXXXXX")"
  "$writer" > "$temporary"
  chmod 644 "$temporary"
  ln "$temporary" "$destination"
  rm -f "$temporary"
  temporary=''
}

if [ ! -d "$app_data/video-generation/models" ]; then
  echo '未找到已安装的视频模型。此脚本只补配置，不下载模型权重。' >&2
  exit 1
fi
models_root="$(cd "$app_data/video-generation/models" && pwd -P)"
found=0
for model in h3-base-fl2va h3-base-ref2va; do
  installed_root="$models_root/$model/$revision"
  [ -d "$installed_root" ] || continue
  installed_root="$(cd "$installed_root" && pwd -P)"
  case "$installed_root/" in
    "$models_root/"*) ;;
    *) echo '模型安装目录位于模型存储范围之外，已停止。' >&2; exit 1 ;;
  esac
  for family in FL2VA Ref2VA; do
    directory="$installed_root/$family/video_vae"
    [ -f "$directory/source/model.safetensors" ] || continue
    directory="$(cd "$directory" && pwd -P)"
    case "$directory/" in
      "$installed_root/"*) ;;
      *) echo '模型配置目录位于模型安装范围之外，已停止。' >&2; exit 1 ;;
    esac
    target="$directory/config.json"
    found=$((found + 1))
    if [ -L "$target" ]; then
      echo "配置文件是符号链接，已停止：$target" >&2
      exit 1
    fi
    if [ -e "$target" ]; then
      if [ -f "$target" ] && [ "$(shasum -a 256 "$target" | awk '{print $1}')" = "$expected" ]; then
        ensure_model_notice "$installed_root/LICENSE" write_model_license
        ensure_model_notice "$installed_root/NOTICE" write_model_notice
        echo "配置已正确：$model / $family"
        continue
      fi
      echo "已有配置与固定版本不一致，未覆盖：$target" >&2
      exit 1
    fi
    temporary="$(mktemp "$directory/.open-media-vae.XXXXXX")"
    write_config > "$temporary"
    if [ "$(shasum -a 256 "$temporary" | awk '{print $1}')" != "$expected" ]; then
      echo '内置配置校验不通过，请重新获取完整修复脚本。原有模型文件未修改。' >&2
      exit 1
    fi
    chmod 644 "$temporary"
    ln "$temporary" "$target"
    rm -f "$temporary"
    temporary=''
    ensure_model_notice "$installed_root/LICENSE" write_model_license
    ensure_model_notice "$installed_root/NOTICE" write_model_notice
    echo "已离线补齐配置：$model / $family"
  done
done
if [ "$found" -eq 0 ]; then
  echo '未找到此固定版本的已安装视频权重，未修改任何模型。' >&2
  exit 1
fi
echo '配置检查完成，原有模型权重保留。重新打开应用后可再次生成。'
