const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require('@playwright/test')

async function main() {
  const { createServer } = await import('vite')
  const server = await createServer({ server: { host: '127.0.0.1', port: 0, strictPort: false }, logLevel: 'error' })
  await server.listen()
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || (fs.existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox', '--no-proxy-server'] })
  try {
    const page = await browser.newPage({ viewport: { width: 980, height: 840 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/__crop_test__', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><head><title>像素框选验证</title></head><body><div id="app"></div></body></html>' }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__crop_test__`)
    await page.evaluate(async () => {
      const { mountImageCropTest } = await import('/tests/browser/image-crop-harness.ts')
      mountImageCropTest()
    })
    const canvas = page.getByRole('group', { name: '图片框选画布，方向键移动选区' })
    await page.locator('.crop-stage img').evaluate(image => image.decode())
    const current = () => page.evaluate(() => window.cropHarness.crop.value)
    async function drag(start, end) {
      const bounds = await canvas.boundingBox()
      const scale = bounds.width / 640
      await page.mouse.move(bounds.x + start.x * scale, bounds.y + start.y * scale)
      await page.mouse.down()
      await page.mouse.move(bounds.x + end.x * scale, bounds.y + end.y * scale, { steps: 5 })
      await page.mouse.up()
    }
    await drag({ x: 50, y: 60 }, { x: 280, y: 210 })
    assert.deepEqual(await current(), { x: 50, y: 60, width: 230, height: 150 })
    await drag({ x: 130, y: 120 }, { x: 150, y: 150 })
    assert.deepEqual(await current(), { x: 70, y: 90, width: 230, height: 150 })
    await canvas.focus()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('Shift+ArrowDown')
    assert.deepEqual(await current(), { x: 71, y: 100, width: 230, height: 150 })
    console.log('PASS source-pixel drawing, moving and keyboard micro-adjustment at fit zoom')

    for (const [label, value] of [['框选X', '32'], ['框选Y', '40'], ['框选宽', '120'], ['框选高', '100']]) {
      await page.getByLabel(label, { exact: true }).fill(value)
      await page.getByLabel(label, { exact: true }).press('Tab')
    }
    assert.deepEqual(await current(), { x: 32, y: 40, width: 120, height: 100 })
    await page.getByLabel('框选预览缩放').selectOption('200')
    await page.getByTestId('crop-viewport').evaluate(element => { element.scrollLeft = 44; element.scrollTop = 60 })
    await page.waitForFunction(() => document.querySelector('.crop-ruler-top text').textContent !== undefined)
    const before = await current()
    await drag({ x: 70, y: 80 }, { x: 81, y: 89 })
    assert.deepEqual(await current(), { x: before.x + 11, y: before.y + 9, width: 120, height: 100 })
    const handle = page.locator('[data-crop-handle="se"]')
    const box = await handle.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2 + 20, { steps: 5 }); await page.mouse.up()
    assert.deepEqual(await current(), { x: 43, y: 49, width: 135, height: 110 })
    assert.equal(await page.locator('.crop-ruler-top').evaluate(element => element.getBoundingClientRect().width), await page.getByTestId('crop-viewport').evaluate(element => element.clientWidth))
    console.log('PASS exact numeric coordinates, scrolled 200% movement, corner resize and aligned source-pixel rulers')

    await drag({ x: 80, y: 80 }, { x: 94, y: 90 })
    const moved = await current()
    const stageBounds = await canvas.boundingBox()
    await page.mouse.move(stageBounds.x + 100 * 2, stageBounds.y + 100 * 2)
    await page.mouse.down(); await page.mouse.move(stageBounds.x + 110 * 2, stageBounds.y + 110 * 2, { steps: 3 })
    await page.keyboard.press('Escape'); await page.mouse.up()
    assert.deepEqual(await current(), moved, 'Escape restores the selection before the active drag')
    await page.getByRole('button', { name: '框选', exact: true }).click()
    await page.getByLabel('框选吸附步长').selectOption('10')
    await drag({ x: 50, y: 50 }, { x: 153, y: 128 })
    assert.deepEqual(await current(), { x: 50, y: 50, width: 100, height: 80 })
    await page.getByLabel('框选X', { exact: true }).fill('9999'); await page.getByLabel('框选X', { exact: true }).press('Tab')
    assert.equal((await current()).x, 540, 'out-of-bounds numeric movement stops at the right edge')
    await page.getByRole('button', { name: '全图', exact: true }).click()
    assert.equal(await current(), undefined)
    await page.getByLabel('框选预览缩放').selectOption('fit')
    console.log('PASS drag cancellation, snap intervals, numeric boundary clamping and full-image reset')

    await page.evaluate(() => { window.cropHarness.crop.value = { x: 40, y: 60, width: 120, height: 100 }; window.cropHarness.disabled.value = true })
    await canvas.dispatchEvent('keydown', { key: 'ArrowRight', bubbles: true })
    assert.deepEqual(await current(), { x: 40, y: 60, width: 120, height: 100 })
    assert.equal(await page.getByLabel('框选X', { exact: true }).isDisabled(), true)
    await page.evaluate(() => { window.cropHarness.disabled.value = false; window.cropHarness.theme.value = 'dark' })
    for (const width of [760, 390, 320]) {
      await page.setViewportSize({ width, height: 840 })
      await page.waitForTimeout(50)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `crop editor fits ${width}px`)
      const heights = await page.locator('select').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().height))
      assert.deepEqual(heights, [32, 32], 'all crop dropdowns use the shared 32px control height')
    }
    assert.deepEqual(errors, [])
    console.log('PASS disabled state, dark theme, narrow widths and consistent 32px dropdown heights')
  } finally { await browser.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
