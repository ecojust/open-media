const assert = require('node:assert/strict')
const { chromium, expect } = require('@playwright/test')

async function main() {
  const { createServer } = await import('vite')
  const server = await createServer({ server: { host: '127.0.0.1', port: 0, strictPort: false, hmr: false, watch: null }, logLevel: 'error' })
  await server.listen()
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || process.env.CHROMIUM_PATH || chromium.executablePath(), headless: true, args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } }), errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(15000)
  try {
    await page.route('**/__mcp_editor__', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><head><style>html,body,#app{height:100%;margin:0}*{box-sizing:border-box}</style></head><body><div id="app"></div></body></html>' }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__mcp_editor__`)
    await page.evaluate(async () => {
      await import('/src/style.css')
      const source = await (await fetch('/src/components/VideoEditor.vue')).text()
      const vueURL = source.match(/from ["']([^"']*\/vue\.js[^"']*)["']/)[1]
      const { createApp, h, shallowRef, ref } = await import(vueURL)
      const Editor = (await import('/src/components/VideoEditor.vue')).default
      const { createProject, createTextClip } = await import('/src/core/project.ts')
      const project = createProject('自动化剪辑预览', { width: 640, height: 360, fps: 30 })
      project.tracks.find(track => track.kind === 'text').clips.push(createTextClip(project, { id: 'caption-1', text: '保持本地编辑与自动化同步', trimOut: 10, fontSize: 24 }))
      const fixture = window.mcpEditorFixture = { editor: ref(null), current: shallowRef(project), automationBusy: ref(false), openCount: 0, busyEvents: [], messages: [], devices: 0 }
      navigator.mediaDevices.getUserMedia = async () => { fixture.devices++; throw new Error('测试禁止设备采集') }
      fixture.app = createApp({ render: () => h(Editor, { ref: fixture.editor, project: fixture.current.value, automationBusy: fixture.automationBusy.value,
        onChange: project => { fixture.current.value = project }, onOpenMcp: () => fixture.openCount++,
        onBusy: value => fixture.busyEvents.push(value), onStatus: value => fixture.messages.push(value),
      }) })
      fixture.app.mount('#app')
    })
    const getState = () => page.evaluate(() => window.mcpEditorFixture.editor.value.getPlayback())
    const busy = () => page.evaluate(() => window.mcpEditorFixture.editor.value.getInteractionBusy())
    const setState = patch => page.evaluate(patch => window.mcpEditorFixture.editor.value.setPlayback(patch), patch)
    await expect(page.getByTestId('editor-mcp-open')).toBeVisible()
    await expect(page.getByTestId('editor-mcp-open-compact')).not.toBeVisible()
    assert.deepEqual(await getState(), { time: 0, playing: false, selectedClipId: '' })
    assert.equal(await busy(), false)
    await page.getByTestId('editor-mcp-open').click()
    assert.equal(await page.evaluate(() => window.mcpEditorFixture.openCount), 1)
    assert.equal(await page.getByTestId('editor-mcp-open').locator('svg path').getAttribute('d'), 'M4 19V5l8 10 8-10v14')
    assert.deepEqual(await setState({ time: 1.5, selectedClipId: 'caption-1' }), { time: 1.5, playing: false, selectedClipId: 'caption-1' })
    await expect(page.locator('[data-clip-id="caption-1"]')).toHaveClass(/selected/)
    await setState({ playing: true })
    await expect.poll(async () => (await getState()).time).toBeGreaterThan(1.6)
    assert.equal((await setState({ playing: false })).playing, false)
    const stopped = await getState()
    const invalid = await page.evaluate(async () => {
      const api = window.mcpEditorFixture.editor.value, errors = []
      for (const patch of [{ time: -1 }, { time: Infinity }, { time: 3, selectedClipId: 'missing' }, { playing: 'yes' }]) {
        try { await api.setPlayback(patch); errors.push('unexpected success') } catch (error) { errors.push(error.message) }
      }
      return errors
    })
    assert.equal(invalid.length, 4)
    assert(!invalid.includes('unexpected success'))
    assert.deepEqual(await getState(), stopped, '无效片段和时间必须在改变任何播放状态前拒绝')
    const text = page.getByTestId('clip-text-content')
    await text.focus()
    assert.equal(await busy(), true)
    await assert.rejects(setState({ time: 2 }), /正在处理操作/)
    await text.fill('输入中的文字不会被外部选择覆盖')
    assert.equal((await setState({ playing: false })).playing, false)
    assert.equal(await page.evaluate(() => window.mcpEditorFixture.current.value.tracks[0].clips[0].text), '输入中的文字不会被外部选择覆盖')
    await text.blur()
    assert.equal(await busy(), false)
    const eventsBefore = await page.evaluate(() => [...window.mcpEditorFixture.busyEvents])
    await page.evaluate(() => { window.mcpEditorFixture.automationBusy.value = true })
    await expect(page.getByTestId('preview-play')).toBeDisabled()
    await expect(text).toBeDisabled()
    assert.equal(await busy(), false, '自动化busy不能反向进入本地busy导致任务锁死')
    await page.getByTestId('editor-mcp-open').click()
    assert.equal(await page.evaluate(() => window.mcpEditorFixture.openCount), 2)
    const beforeSelection = await getState()
    assert.deepEqual(await setState({ selectedClipId: '' }), { ...beforeSelection, selectedClipId: '' }, '内部素材提交完成后可在任务解锁前同步选中，不改变播放时间或状态')
    assert.deepEqual(await setState({ selectedClipId: 'caption-1' }), beforeSelection)
    await assert.rejects(setState({ time: 2 }), /正在处理操作/)
    await setState({ playing: false })
    await page.setViewportSize({ width: 760, height: 820 })
    await expect(page.getByTestId('editor-mcp-open')).not.toBeVisible()
    await expect(page.getByTestId('editor-mcp-open-compact')).toBeVisible()
    await page.getByTestId('editor-mcp-open-compact').click()
    assert.equal(await page.evaluate(() => window.mcpEditorFixture.openCount), 3)
    await page.evaluate(() => { window.mcpEditorFixture.automationBusy.value = false })
    await expect(page.getByTestId('preview-play')).toBeEnabled()
    assert.deepEqual(await page.evaluate(() => window.mcpEditorFixture.busyEvents), eventsBefore, '自动化busy不能触发本地busy事件回路')
    await page.setViewportSize({ width: 1440, height: 960 })
    await page.getByRole('button', { name: '项目设置', exact: true }).click()
    assert.equal(await busy(), true)
    await assert.rejects(setState({ selectedClipId: '' }), /正在处理操作/)
    await page.getByRole('button', { name: '关闭项目设置', exact: true }).click()
    assert.equal(await busy(), false)
    const trackHandle = page.locator('.track-drag-handle').first(), handleBounds = await trackHandle.boundingBox()
    await page.mouse.move(handleBounds.x + handleBounds.width / 2, handleBounds.y + handleBounds.height / 2)
    await page.mouse.down()
    assert.equal(await busy(), true, '轨道拖动中不可远程替换项目')
    await page.mouse.up()
    assert.equal(await busy(), false)
    const clip = page.locator('[data-clip-id="caption-1"]'), clipBounds = await clip.boundingBox()
    await page.mouse.move(clipBounds.x + 25, clipBounds.y + 10)
    await page.mouse.down()
    assert.equal(await busy(), true, '片段拖动中不可远程替换项目')
    await page.mouse.up()
    const dividerBounds = await page.getByTestId('timeline-divider').boundingBox()
    await page.mouse.move(dividerBounds.x + dividerBounds.width / 2, dividerBounds.y + dividerBounds.height / 2)
    await page.mouse.down()
    assert.equal(await busy(), true, '时间线高度调整也是进行中的本地交互')
    await page.mouse.up()
    await setState({ selectedClipId: '', time: 0 })
    assert.deepEqual(await getState(), { time: 0, playing: false, selectedClipId: '' })
    assert.equal(await page.evaluate(() => window.mcpEditorFixture.devices), 0, '远程播放不应申请摄像头或麦克风')
    assert.deepEqual(errors, [])
    console.log('PASS MCP剪辑桥：M入口与窄屏入口、自动化任务不锁死入口、不回传busy、真实预览播放/暂停/选择、输入与拖动冲突保护、禁止设备采集')
  } finally { await browser.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
