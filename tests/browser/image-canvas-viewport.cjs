const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium, expect } = require('@playwright/test')

async function main() {
  const { createServer } = await import('vite')
  const server = await createServer({ server: { host: '127.0.0.1', port: 0, strictPort: false, watch: { ignored: () => true } }, logLevel: 'error' })
  await server.listen()
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || (fs.existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox', '--no-proxy-server'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1000, height: 800 } })
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.route('**/__image_viewport_test__', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><body><div id="app"></div></body></html>' }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__image_viewport_test__`)
    await page.evaluate(async () => { const { mountImageCanvasViewportTest } = await import('/tests/browser/image-canvas-viewport-harness.ts'); mountImageCanvasViewportTest() })
    const viewport = page.getByTestId('image-canvas-viewport'), stage = page.getByTestId('image-canvas-stage')
    const current = () => page.evaluate(() => ({ ...window.imageViewportHarness.view.value }))
    const edits = () => page.evaluate(() => window.imageViewportHarness.edits.value)
    await expect(stage).toBeVisible()
    const initial = await current()
    assert.ok(initial.scale > 0 && initial.scale < 1)
    assert.equal(await stage.evaluate(element => element.style.width), '1600px')
    assert.equal(await page.getByTestId('editable-source').getAttribute('width'), '320', 'view scale is independent of the canvas backing resolution')
    const bounds = await viewport.boundingBox()
    const anchor = { x: bounds.x + 420, y: bounds.y + 120 }
    await page.mouse.move(anchor.x, anchor.y)
    await page.keyboard.down('Control'); await page.mouse.wheel(0, -80); await page.keyboard.up('Control')
    await expect.poll(async () => (await current()).scale).toBeGreaterThan(initial.scale)
    const zoomed = await current()
    assert.ok(Math.abs((420 - initial.offsetX) / initial.scale - (420 - zoomed.offsetX) / zoomed.scale) < .001)
    assert.ok(Math.abs((120 - initial.offsetY) / initial.scale - (120 - zoomed.offsetY) / zoomed.scale) < .001)
    await page.mouse.wheel(35, 50)
    await expect.poll(async () => (await current()).offsetX).toBe(zoomed.offsetX - 35)
    assert.equal((await current()).offsetY, zoomed.offsetY - 50)
    assert.equal(await edits(), 0)
    console.log('PASS initial fit, source-sized stage and canvas backing independence, anchored zoom and wheel pan')

    await page.getByRole('button', { name: '适应画布', exact: true }).click()
    const source = page.getByTestId('editable-source')
    const sourceBounds = await source.boundingBox()
    const point = { x: sourceBounds.x + 35, y: sourceBounds.y + 35 }
    await page.mouse.click(point.x, point.y)
    assert.equal(await edits(), 1, 'ordinary left input reaches the editing surface')
    async function drag(dx, dy, button = 'left') {
      const rectangle = await source.boundingBox()
      const start = { x: rectangle.x + 35, y: rectangle.y + 35 }
      await page.mouse.move(start.x, start.y); await page.mouse.down({ button }); await page.mouse.move(start.x + dx, start.y + dy, { steps: 3 }); await page.mouse.up({ button })
    }
    await viewport.focus(); await page.keyboard.down('Space')
    const beforePan = await current(); await drag(65, 30); await page.keyboard.up('Space')
    assert.equal((await current()).offsetX, beforePan.offsetX + 65)
    assert.equal(await edits(), 1, 'Space drag does not edit')
    await viewport.focus(); await page.keyboard.press('h'); await drag(20, 20)
    assert.equal(await edits(), 1, 'hand drag does not edit')
    await page.keyboard.press('v'); await drag(0, 0)
    assert.equal(await edits(), 2, 'select shortcut restores normal editing')
    await drag(-20, -20, 'middle'); assert.equal(await edits(), 2, 'middle drag does not edit')
    await page.evaluate(() => { window.imageViewportHarness.readonly.value = true })
    await drag(15, 10); assert.equal(await edits(), 2, 'readonly left drag only navigates')
    await page.evaluate(() => { window.imageViewportHarness.readonly.value = false })
    await viewport.focus(); await page.keyboard.down('Space')
    const handle = await page.getByTestId('source-resize-handle').boundingBox()
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
    await page.mouse.down(); await page.mouse.move(handle.x + 30, handle.y + 30, { steps: 3 }); await page.mouse.up(); await page.keyboard.up('Space')
    assert.equal(await page.evaluate(() => window.imageViewportHarness.handleEdits.value), 0, 'panning on a resize handle suppresses pointer editing and its follow-up click')
    console.log('PASS editing input preservation, Space/hand/middle/read-only panning and selection shortcut')

    await page.getByRole('button', { name: '适应画布', exact: true }).click()
    const text = page.getByLabel('画布文字')
    await text.fill(''); await text.press('h'); await text.press('Space'); await text.press('v')
    assert.equal(await text.inputValue(), 'h v')
    assert.equal(await page.getByRole('button', { name: '手形工具', exact: true }).getAttribute('aria-pressed'), 'false')
    assert.deepEqual(await current(), initial)
    await viewport.focus(); await page.keyboard.down('Space')
    await page.evaluate(() => window.dispatchEvent(new Event('blur')))
    await page.keyboard.up('Space')
    assert.equal(await viewport.evaluate(element => element.classList.contains('can-pan')), false)
    await page.getByTestId('external-tool').click()
    const sourceArea = await source.boundingBox()
    await page.mouse.move(sourceArea.x + 30, sourceArea.y + 30)
    await page.keyboard.down('Space')
    assert.equal(await viewport.evaluate(element => element.classList.contains('can-pan')), true, 'hovering the canvas enables Space pan after a property button was selected')
    await page.keyboard.up('Space')
    await page.getByLabel('外部属性').focus()
    await page.keyboard.press('Space'); await page.keyboard.press('h')
    assert.equal(await page.getByLabel('外部属性').inputValue(), ' h', 'hover shortcuts never steal typing from an external property input')
    assert.equal(await viewport.evaluate(element => element.classList.contains('can-pan')), false)
    console.log('PASS input shortcuts remain text and window blur releases temporary panning')

    await page.getByRole('button', { name: '画布实际大小', exact: true }).click()
    const beforeResize = await current()
    await page.evaluate(() => { window.imageViewportHarness.size.value = 500 })
    await expect.poll(async () => (await current()).viewportWidth).toBe(500)
    const resized = await current()
    assert.equal(resized.scale, 1)
    assert.equal((beforeResize.viewportWidth / 2 - beforeResize.offsetX), (resized.viewportWidth / 2 - resized.offsetX))
    await page.getByRole('button', { name: '适应画布', exact: true }).click()
    await page.evaluate(() => { window.imageViewportHarness.size.value = 650 })
    await expect.poll(async () => (await current()).viewportWidth).toBe(650)
    assert.ok((await current()).scale > resized.scale / 3)
    await page.evaluate(() => { window.imageViewportHarness.width.value = 640; window.imageViewportHarness.height.value = 360 })
    await expect.poll(async () => await stage.evaluate(element => element.style.width)).toBe('640px')
    assert.ok((await current()).offsetX >= 40)
    await page.evaluate(() => { window.imageViewportHarness.disabled.value = true })
    const disabled = await current()
    await viewport.focus(); await page.keyboard.press('h'); await page.mouse.move(bounds.x + 200, bounds.y + 150); await page.mouse.wheel(30, 30)
    await expect(page.getByRole('button', { name: '放大画布', exact: true })).toBeDisabled()
    assert.deepEqual(await current(), disabled)
    await page.setViewportSize({ width: 320, height: 700 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert.deepEqual(errors, [])
    console.log('PASS resize preserves source center, fit follows dimensions, disabled state and narrow layout')
  } finally { await browser.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
