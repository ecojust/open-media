const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync, existsSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const { chromium, expect } = require('@playwright/test')

async function main() {
  const { createServer } = await import('vite')
  const artifacts = process.env.BROWSER_ARTIFACTS || '/tmp/open-media-general-materials'
  mkdirSync(artifacts, { recursive: true })
  const server = await createServer({ cacheDir: `${artifacts}/vite`, server: { host: '127.0.0.1', port: 0, hmr: false, watch: null }, logLevel: 'error' })
  await server.listen()
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : chromium.executablePath()), headless: true, args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  page.setDefaultTimeout(25000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.addInitScript(() => { localStorage.setItem('open-media:theme', 'dark'); localStorage.setItem('open-media:autosave', 'true') })
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`)
    await expect(page.getByTestId('home-workspace')).toBeVisible()
    const catalog = await page.evaluate(async () => {
      const { createProject, createClip } = await import('/src/core/project.ts')
      const { saveProject } = await import('/src/core/storage.ts')
      const { importMediaFile } = await import('/src/core/media-import.ts')
      const { VIDEO_SEGMENTS } = await import('/src/core/video-segment-catalog.ts')
      const { WATERMARK_MATERIALS } = await import('/src/core/watermark-library.ts')
      const source = VIDEO_SEGMENTS.find(item => item.collection === 'general')
      const blob = await (await fetch(source.url)).blob()
      const asset = await importMediaFile(new File([blob], '示例画面.webm', { type: 'video/webm' }))
      const project = createProject('通用剪辑样式', { width: 640, height: 360, fps: 24 })
      project.assets.push(asset)
      project.tracks.find(track => track.kind === 'video').clips.push(createClip(asset, project, { id: 'part-a', trimOut: 2.5, volume: 0 }), createClip(asset, project, { id: 'part-b', start: 2.5, trimIn: 2.5, trimOut: 5, volume: 0 }))
      await saveProject(project, new Map([[asset.id, blob]])); localStorage.setItem('open-media:last-project', project.id)
      return WATERMARK_MATERIALS.filter(item => item.collection === 'general')
    })
    assert.equal(catalog.length, 24)
    await page.reload(); await expect(page.getByTestId('home-workspace')).toBeVisible(); await page.getByTestId('nav-edit').click()
    await expect(page.getByTestId('video-editor')).toBeVisible()
    await page.getByTestId('watermark-open').click()
    await expect(page.getByTestId('watermark-collection-general')).toHaveAttribute('aria-pressed', 'true')
    await expect(page.locator('[data-watermark-id]')).toHaveCount(24)
    await page.locator('[data-watermark-id] img').evaluateAll(async images => { for (const image of images) { image.loading = 'eager'; await image.decode() } })
    await page.screenshot({ path: `${artifacts}/general-library.png` })
    await page.locator(`[data-watermark-add="${catalog[0].id}"]`).click()
    const customizer = page.getByTestId('watermark-customizer')
    await expect(customizer).toBeVisible()
    await customizer.getByLabel('水印文字', { exact: true }).fill('让每一段内容，都有清晰的表达')
    await customizer.getByLabel('水印文字颜色').fill('#edbd72')
    await customizer.getByLabel('水印时长').fill('3')
    await customizer.getByLabel('水印位置').selectOption('bottom-center')
    await customizer.getByLabel('水印动画').selectOption('slide-up')
    const hash = () => customizer.locator('canvas').evaluate(canvas => { const pixels = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data; let value = 0; for (let i = 0; i < pixels.length; i += 4) value = (value * 31 + pixels[i] + pixels[i + 3]) >>> 0; return value })
    const held = await hash()
    await customizer.getByRole('button', { name: '播放动画' }).click()
    await expect.poll(hash, { intervals: [30] }).not.toBe(held)
    await expect(customizer.getByRole('button', { name: '播放动画' })).toBeVisible()
    await customizer.getByLabel('水印动画').selectOption('push-in')
    await page.screenshot({ path: `${artifacts}/general-customizer.png` })
    await customizer.getByTestId('watermark-customizer-add').click()
    await expect(customizer).toHaveCount(0)
    await expect(page.locator('.property-panel textarea')).toHaveValue('让每一段内容，都有清晰的表达')
    await page.getByTestId('motion-preset-controls').locator('summary').click()
    await page.getByLabel('片段入退场动画预设').selectOption('pull-back')
    await page.getByTestId('motion-preset-apply').click()
    await page.getByTestId('watermark-open').click()
    await page.getByTestId('watermark-collection-science').click()
    await expect(page.locator('[data-watermark-id]')).toHaveCount(24)
    await page.getByTestId('watermark-collection-all').click()
    await expect(page.locator('[data-watermark-category="全部"]')).toContainText('548')
    await page.getByRole('button', { name: '关闭添加水印', exact: true }).click()
    await page.getByTestId('transition-open').click()
    await page.getByRole('button', { name: '方向移动 6', exact: true }).click()
    await page.locator('.transition-card').filter({ has: page.locator('input[value="slide-left"]') }).click()
    await page.getByLabel('转场方向', { exact: true }).selectOption('down')
    await page.getByLabel('转场动画节奏').selectOption('ease-out')
    await page.getByLabel('转场作用范围').selectOption('both')
    await page.screenshot({ path: `${artifacts}/general-transitions.png` })
    await page.getByTestId('transition-apply').click()
    await expect(page.getByTestId('transition-library')).toHaveCount(0)
    await expect(page.locator('.statusbar>button')).toHaveText('本地草稿已保存')
    const encoded = await page.evaluate(async () => {
      const { loadProject } = await import('/src/core/storage.ts')
      const { exportTimelineWebM } = await import('/src/core/browser-export.ts')
      const loaded = await loadProject(localStorage.getItem('open-media:last-project'))
      try {
        const clips = loaded.project.tracks.flatMap(track => track.clips)
        const text = clips.find(clip => clip.text === '让每一段内容，都有清晰的表达')
        if (!text || text.color !== '#edbd72' || text.trimOut !== 3 || text.keyframes?.scaleX?.[0]?.value !== 1.06) throw Error('定制文字及右侧重新应用的动画未完整保存')
        const transition = clips.find(clip => clip.transition)?.transition
        if (transition?.direction !== 'down' || transition.easing !== 'ease-out') throw Error('转场参数未保存')
        const blob = await exportTimelineWebM(loaded.project, { width: 640, height: 360, fps: 24, videoBitsPerSecond: 1500000 })
        return Array.from(new Uint8Array(await blob.arrayBuffer()))
      } finally { loaded.revoke() }
    })
    const file = `${artifacts}/general-demo.webm`; writeFileSync(file, Buffer.from(encoded))
    execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-f', 'null', '-'], { stdio: 'pipe' })
    const decoded = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height:packet=pts_time,duration_time', '-of', 'json', file], { encoding: 'utf8' }))
    assert.equal(decoded.streams[0].width, 640)
    const end = Math.max(...decoded.packets.map(packet => Number(packet.pts_time) + Number(packet.duration_time || 0)))
    assert(end > 4.8 && end < 5.3)
    assert(encoded.length > 1000); assert.deepEqual(errors, [])
    console.log('PASS 通用模板真实定制与动画预览、旧库可达、保存重开、转场参数及5秒真实WebM完整解码')
  } catch (error) { await page.screenshot({ path: `${artifacts}/failure.png` }).catch(() => {}); throw error }
  finally { await browser.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
