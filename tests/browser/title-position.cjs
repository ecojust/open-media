const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium, expect } = require('@playwright/test')

async function main() {
  const { createServer } = await import('vite')
  const server = await createServer({ server: { host: '127.0.0.1', port: 0, strictPort: false, hmr: false, watch: null }, logLevel: 'error' })
  await server.listen()
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || chromium.executablePath(), headless: true, args: ['--no-sandbox'] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = []
  page.on('pageerror', error => errors.push(error.message))
  const directory = process.env.BROWSER_ARTIFACTS ? path.join(process.env.BROWSER_ARTIFACTS, 'title-position') : '/tmp/open-media-title-position'
  fs.mkdirSync(directory, { recursive: true })
  try {
    await page.route('**/__title_position__', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1"><style>html,body,#app,.app-shell{height:100%;margin:0}*{box-sizing:border-box}</style></head><body><div id="app"></div></body></html>' }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__title_position__`)
    await page.evaluate(async () => {
      await import('/src/style.css')
      const component = await (await fetch('/src/components/VideoEditor.vue')).text()
      const vue = component.match(/from ["']([^"']*\/vue\.js[^"']*)["']/)[1]
      const { createApp, h, ref, shallowRef, nextTick } = await import(vue)
      const { createProject } = await import('/src/core/project.ts')
      const { executeProjectTool } = await import('/src/core/mcp-tools.ts')
      const { createHistory, commitHistory, undoHistory } = await import('/src/core/timeline.ts')
      const Editor = (await import('/src/components/VideoEditor.vue')).default
      const project = createProject('动画标题定位', { width: 1080, height: 1920, fps: 24, background: '#000000' })
      const current = shallowRef(project), editor = ref(), theme = ref('light')
      let history = createHistory(project)
      const fixture = window.titlePosition = { current, editor, theme, changes: 0, nextTick, undo() { history = undoHistory(history); current.value = history.present } }
      const commit = next => { history = commitHistory(history, next); current.value = next; fixture.changes++ }
      fixture.app = createApp({ render: () => h('div', { class: 'app-shell', 'data-theme': theme.value }, h(Editor, {
        ref: editor, project: current.value, onChange: commit,
        runTool: async (name, args, options) => { options.signal.throwIfAborted(); const result = executeProjectTool(current.value, name, args); if (result.project) commit(result.project); await nextTick(); return result.data },
      })) })
      fixture.app.mount('#app')
    })
    const state = () => page.evaluate(() => JSON.parse(JSON.stringify(window.titlePosition.current.value)))
    const title = async () => (await state()).tracks.flatMap(track => track.clips).find(clip => clip.text === '精确定位动画标题')
    const changes = () => page.evaluate(() => window.titlePosition.changes)
    await page.getByTestId('visual-elements-open').click()
    const dialog = page.getByRole('dialog', { name: '标注与标题', exact: true })
    await dialog.getByRole('button', { name: '动态标题', exact: true }).click()
    await dialog.getByLabel('动态标题布局').selectOption('corner')
    await dialog.getByText('位置与尺寸', { exact: true }).click()
    assert(Math.abs(Number(await dialog.getByLabel('标题垂直位置').inputValue()) - 115.2) < 1e-8)
    await dialog.getByLabel('标题水平位置').fill('100')
    await dialog.getByLabel('标题垂直位置').fill('1510')
    await dialog.getByLabel('标题区域宽度').fill('880')
    await dialog.getByLabel('标题区域高度').fill('240')
    await dialog.getByLabel('标题字号').fill('64')
    await dialog.getByLabel('动态标题文字').fill('精确定位动画标题')
    await dialog.getByLabel('标题进入动画').selectOption('slide')
    await dialog.getByRole('button', { name: '添加到时间线', exact: true }).click()
    await expect.poll(async () => (await title())?.y).toBe(1510)
    const created = await title()
    assert.deepEqual([created.x, created.y, created.width, created.height], [100, 1510, 880, 240])
    assert.deepEqual(created.keyframes.y.map(frame => frame.value), [1606, 1510])
    assert.equal(await changes(), 1)
    await page.screenshot({ path: path.join(directory, 'title-layout-light.png') })
    await page.getByRole('button', { name: '关闭标注与标题', exact: true }).click()
    await page.locator(`.timeline-clip[data-clip-id="${created.id}"]`).click()
    await page.evaluate(async () => { window.titlePosition.editor.value.seek(1); await window.titlePosition.nextTick() })
    const sync = page.getByRole('checkbox', { name: '移动时同步位置关键帧' })
    await expect(sync).toBeChecked()
    const original = await state(), beforeMove = await changes()
    const y = page.locator('.property-content').getByLabel('Y', { exact: true })
    await y.fill('1200'); await y.press('Tab')
    await expect.poll(async () => (await title()).keyframes.y.at(-1).value).toBe(1200)
    assert.equal(await changes(), beforeMove + 1)
    assert.equal((await title()).keyframes.y[0].value, 1296)
    const pixel = (x, y) => page.getByTestId('video-preview').evaluate((canvas, { x, y }) => [...canvas.getContext('2d').getImageData(Math.round(x / 1080 * canvas.width), Math.round(y / 1920 * canvas.height), 1, 1).data], { x, y })
    await expect.poll(() => pixel(120, 1220)).toEqual([21, 34, 56, 255])
    await expect.poll(() => pixel(120, 1530)).toEqual([0, 0, 0, 255])
    await page.evaluate(() => window.titlePosition.undo())
    assert.deepEqual(await state(), original, '一次撤销同时恢复位置及动画曲线')
    await expect.poll(() => pixel(120, 1530)).toEqual([21, 34, 56, 255])
    await sync.uncheck(); await y.fill('1200'); await y.press('Tab')
    await expect.poll(async () => (await title()).y).toBe(1200)
    assert.equal((await title()).keyframes.y.at(-1).value, 1510)
    await expect.poll(() => pixel(120, 1530)).toEqual([21, 34, 56, 255])
    await page.evaluate(() => window.titlePosition.undo())
    await sync.check()
    const handle = page.getByTestId('preview-selected-clip')
    await handle.focus(); await page.keyboard.press('Shift+ArrowUp')
    await expect.poll(async () => (await title()).y).toBe(1500)
    assert.equal((await title()).keyframes.y.at(-1).value, 1500)
    const beforeDrag = await changes(), bounds = await handle.boundingBox()
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
    await page.mouse.down(); await page.keyboard.down('Alt')
    await page.mouse.move(bounds.x + bounds.width / 2 + 8, bounds.y + bounds.height / 2 - 15, { steps: 5 })
    await page.mouse.up(); await page.keyboard.up('Alt')
    await expect.poll(changes).toBe(beforeDrag + 1)
    const dragged = await title()
    assert(Math.abs(dragged.y - dragged.keyframes.y.at(-1).value) < 1e-6)
    assert(Math.abs(dragged.keyframes.y[0].value - dragged.y - 96) < 1e-6)
    await page.evaluate(() => { window.titlePosition.theme.value = 'dark' })
    await sync.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(directory, 'position-sync-dark.png') })
    assert.deepEqual(errors, [])
    console.log('PASS 自定义标题坐标/尺寸与滑入终点；属性、方向键和预览拖动同步曲线；关闭同步保留绝对动画；真实画布像素与一次撤销验证')
    console.log(`Screenshots: ${directory}`)
  } finally { await browser.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
